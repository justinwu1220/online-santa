package com.onlinesanta.storage;

/**
 * 依敏感度區分的兩個儲存空間。
 *
 * <p>把「公開」與「私密」放在不同的 bucket，而不是同一個 bucket 靠程式判斷：
 * 設錯權限的後果是孩童照片外流，這種事不該只靠應用層的 if 判斷把關。
 * 分成兩個 bucket 之後，「哪些檔案可以被公開存取」是一個基礎設施層級的事實。
 *
 * <p>另有一個現實考量：願望牆是上架首日流量最高的頁面。公開 bucket 的檔案用固定
 * 網址直接讀取，不需要簽章；私密檔案每次都要簽，而 Cloud Run 上簽章要呼叫 IAM
 * signBlob API（一次網路往返），一頁 20 個願望就是 20 次往返，撐不住尖峰。
 */
public enum StorageBucket {

    /**
     * 公開可讀：僅存放禮物示意圖。
     *
     * <p>示意圖拍的是玩具或書本，不含孩童影像，公開沒有隱私風險。
     */
    PUBLIC,

    /**
     * 一律需要簽章才能讀取：寄送證明（可能含捐贈者姓名地址）與機構回饋照片
     * （可能含孩童影像）。
     */
    PRIVATE
}
